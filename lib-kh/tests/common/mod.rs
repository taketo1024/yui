//! strongly-invertible slice "cork" knots (9_46, 15n_103488, 17nh_73), their mirrors, and the
//! interlocks `K ∥ K'` joined by the universal clasp. `from_symmetric_pd_code` installs the standard
//! strong inversion; `Cut` is the τ-symmetric head/clasp chunk cut for the interlock.
