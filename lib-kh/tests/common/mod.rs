// ---- constructors --------------------------------------------------------------------------------

/// Build the strongly-invertible link (standard strong inversion) from a symmetric PD.
pub fn inv(pd: Pd) -> InvLink {
    InvLink::from_symmetric_pd_code(pd)
}

/// Build the underlying (un-involutive) link from a PD.
pub fn link(pd: Pd) -> Link {
    Link::from_pd_code(pd)
}
