//! Interlock computations — `ssi` of `K ∥ K'`, two strongly invertible cork knots joined by the
//! universal clasp, and the stacked variants.
//!
//! **Not published.** `invkh1.rs` / `invkh2.rs` mirror the two papers; this file is the working
//! record of the interlock experiments, kept because the values are expensive to recompute. If
//! these results reach a paper, move them into the matching file and label them by claim.
//!
//! Everything here is `#[ignore]`d:
//!
//! ```text
//! cargo test -r -p yui-kh --test invkh3 -- --ignored --nocapture interlock_9_46
//! ```
//!
//! The observed pattern: a single cork has `ssi = (0, 2)`, an interlock of two has `(0, 4)`, and
//! stacking three does **not** give `(0, 6)` — it saturates at `(0, 4)`. PD codes are at the
//! bottom of the file.

use yui_kh::tng::builder::CutOption;
use yui_link::InvLink;

mod common;
use common::*;

fn assert_interlock_ssi(l: InvLink, expected: (i32, i32)) {
    println!("interlock: {} crossings, writhe {}", l.inner().n_crossings(), l.writhe());
    assert_ssi(&l, cut_config(CutOption::Auto(2)), Side::Positive, expected);
}

#[test]
#[ignore = "interlock 9_46 ∥ 9_46 (30 cr): ssi = (0, 4)"]
fn interlock_9_46() {
    init_logger();
    assert_interlock_ssi(inv_interlock_9_46(), (0, 4));
}

#[test]
#[ignore = "interlock 9_46 ∥ 15n_103488 (36 cr): ssi = (0, 4)"]
fn interlock_9_46_15n() {
    init_logger();
    assert_interlock_ssi(inv_interlock_9_46_15n(), (0, 4));
}

#[test]
#[ignore = "interlock 15n_103488 ∥ 15n_103488 (42 cr): ssi = (0, 4)"]
fn interlock_15n() {
    init_logger();
    assert_interlock_ssi(inv_interlock_15n(), (0, 4));
}

#[test]
#[ignore = "interlock 17nh_73 ∥ 17nh_73 (48 cr): ssi = (0, 4); heavy"]
fn interlock_17nh() {
    init_logger();
    assert_interlock_ssi(inv_interlock_17nh(), (0, 4));
}

#[test]
#[ignore = "stacked 3x 9_46 (51 cr): ssi = (0, 4), NOT (0, 6) — the stacking saturates; heavy"]
fn stack3_9_46() {
    init_logger();
    assert_interlock_ssi(inv_stack3_9_46(), (0, 4));
}

