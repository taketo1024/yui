impl Braid {
    pub fn test_data(name: &str) -> Braid {
        let word: &[i32] = match name {
            "3_1" => &[1, 1, 1],
            "4_1" => &[1, -2, 1, -2],
            "5_1" => &[1, 1, 1, 1, 1],
            "5_2" => &[1, 1, 1, 2, -1, 2],
            "6_1" => &[1, 1, 2, -1, -3, 2, -3],
            "6_2" => &[1, 1, 1, -2, 1, -2],
            "6_3" => &[1, 1, -2, 1, -2, -2],
            _ => panic!("no test data for `{name}`"),
        };
        Braid::from_iter(word.iter().copied())
    }
}

